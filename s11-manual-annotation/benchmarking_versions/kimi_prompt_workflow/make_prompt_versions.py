#!/opt/homebrew/bin/python3.13
"""P0: rule-level changes between the extraction prompt versions, and the metrics of the runs that used each version.

Input : work/eval/llm-service.*.js (prompt = the template literal from `promptTemplate = `You are a scientific data
        extraction assistant` to `Return ONLY valid JSON, no additional text.`), work/eval/leaderboard.csv (28 all).
Output: work/eval/PROMPT_VERSIONS.md (tables and hunks; the hand-written reading is work/eval/PROMPT_VERSIONS_reading.md,
        prepended when present).

  python3.13 work/eval/make_prompt_versions.py          write the report
  python3.13 work/eval/make_prompt_versions.py --control  self-test: a deliberately altered prompt must produce hunks,
                                                          an identical one none (exit 1 if the control does not behave)
"""
import csv, difflib, re, statistics, sys
from collections import defaultdict
from pathlib import Path

EVAL = Path(__file__).resolve().parent
START = 'promptTemplate = `You are a scientific data extraction assistant'
END = 'Return ONLY valid JSON, no additional text.'
ANNOTATION = 'manual annotation B'   # the only annotation that covers all entries

# (key, module, leaderboard label)
VERSIONS = [
    ('deployed', 'llm-service.deployed.js', 'deployed prompt'),
    ('v1',       'llm-service.local-perrow.js', 'per-row prompt v1'),
    ('v2',       'llm-service.local-v2.js', 'general prompt v2'),
    ('v3',       'llm-service.local-v3.js', 'general prompt v3'),
    ('v4',       'llm-service.local-v4.js', 'general prompt v4'),
    ('v5',       'llm-service.local-v5.js', 'general prompt v5'),
    ('v6',       'llm-service.local-v6.js', 'general prompt v6'),
    ('v7',       'llm-service.local-v7.js', 'evidence prompt v7'),
    ('v7.1',     'llm-service.local-v71.js', 'evidence prompt v7.1 (table quoting)'),
]


def prompt_lines(module):
    lines = (EVAL / module).read_text().split('\n')
    a = next(i for i, l in enumerate(lines) if START in l)
    b = next(i for i, l in enumerate(lines) if l.startswith(END))
    return [l.rstrip() for l in lines[a:b + 1] if l.strip()]


def hunks(old, new):
    out = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, old, new, autojunk=False).get_opcodes():
        if tag != 'equal':
            out.append((old[i1:i2], new[j1:j2]))
    return out


def fmt_hunk(h):
    rem, add = h
    s = ''
    if rem:
        s += '    removed:\n' + ''.join(f'    - {l.strip()}\n' for l in rem)
    if add:
        s += '    added:\n' + ''.join(f'    + {l.strip()}\n' for l in add)
    return s


def load_runs():
    by = defaultdict(list)   # (label, model, case) -> rows
    for r in csv.DictReader(open(EVAL / 'leaderboard.csv')):
        if r['annotation'] == ANNOTATION:
            by[(r['prompt'], r['model'], r['case'])].append(r)
    return by


def stats(rows):
    f1 = [float(r['record_f1'] or 0) if r['status'] == 'ok' else 0.0 for r in rows]
    tr = [float(r['traceable_share']) for r in rows if r['status'] == 'ok' and r['traceable_share'] != '']
    return dict(n=len(rows), failed=sum(r['status'] != 'ok' for r in rows), f1=statistics.mean(f1),
                sd=statistics.stdev(f1) if len(f1) > 1 else None,
                tr=statistics.mean(tr) if tr else None)


def run_report():
    by = load_runs()
    md = []
    reading = EVAL / 'PROMPT_VERSIONS_reading.md'
    md.append('# Prompt versions: rule changes and the metrics of the runs that used them\n')
    md.append('Generated by `work/eval/make_prompt_versions.py` from the prompt text of the modules `work/eval/llm-service.*.js` and from '
              '`leaderboard.csv` (record F1 and traceable share against the manual annotation B annotation; a failed run counts 0 for F1 and is excluded from '
              'the traceable mean; `n` = runs, `F` = failed runs).\n')
    if reading.exists():
        md.append(reading.read_text() + '\n')
    prompts = {k: prompt_lines(m) for k, m, _ in VERSIONS}
    md.append('## 1. Rule-level diff to the previous version\n')
    for (k0, _, _), (k1, _, _) in zip(VERSIONS, VERSIONS[1:]):
        hs = hunks(prompts[k0], prompts[k1])
        md.append(f'### {k0} -> {k1}  ({len(hs)} hunks, {len(prompts[k0])} -> {len(prompts[k1])} non-empty lines)\n')
        md.append('```\n' + ''.join(f'  hunk {i + 1}\n{fmt_hunk(h)}' for i, h in enumerate(hs)) + '```\n')
    md.append('## 2. Metrics per version, model and entry\n')
    md.append('| Version | Model | Entry | n | F | Record F1 (mean ± sd) | Traceable |\n|---|---|---|---|---|---|---|')
    rows_by_version = {}
    for k, _, label in VERSIONS:
        cells = {(m, c): stats(v) for (p, m, c), v in by.items() if p == label}
        rows_by_version[k] = cells
        for (m, c), s in sorted(cells.items()):
            sd = f' ± {s["sd"]:.3f}' if s['sd'] is not None else ''
            tr = f'{s["tr"]:.2f}' if s['tr'] is not None else '-'
            md.append(f'| {k} | {m} | {c} | {s["n"]} | {s["failed"]} | {s["f1"]:.3f}{sd} | {tr} |')
    md.append('\n## 3. Change per transition, same model and entry\n')
    md.append('"within spread" = |ΔF1| below the larger sd of the two cells, or either cell has n = 1 (the data cannot tell).\n')
    md.append('| Transition | Model | Entry | F1 before (n) | F1 after (n) | ΔF1 | Δ traceable | Verdict |\n|---|---|---|---|---|---|---|---|')
    for (k0, _, _), (k1, _, _) in zip(VERSIONS, VERSIONS[1:]):
        a, b = rows_by_version[k0], rows_by_version[k1]
        for key in sorted(set(a) & set(b)):
            x, y = a[key], b[key]
            d = y['f1'] - x['f1']
            spread = max(s for s in (x['sd'], y['sd'], 0.0) if s is not None)
            verdict = 'within spread' if (x['n'] == 1 or y['n'] == 1 or abs(d) < spread) else ('better' if d > 0 else 'worse')
            dt = f'{y["tr"] - x["tr"]:+.2f}' if x['tr'] is not None and y['tr'] is not None else '-'
            md.append(f'| {k0} -> {k1} | {key[0]} | {key[1]} | {x["f1"]:.3f} ({x["n"]}) | {y["f1"]:.3f} ({y["n"]}) | {d:+.3f} | {dt} | {verdict} |')
    (EVAL / 'PROMPT_VERSIONS.md').write_text('\n'.join(md) + '\n')
    print('wrote', EVAL / 'PROMPT_VERSIONS.md')


def control():
    base = prompt_lines('llm-service.local-v7.js')
    assert hunks(base, list(base)) == [], 'identical prompts must give no hunks'
    altered = list(base)
    altered.insert(10, 'CONTROL LINE that is not in any prompt')
    del altered[20]
    hs = hunks(base, altered)
    ok = len(hs) == 2 and any('CONTROL LINE' in l for h in hs for l in h[1]) and any(h[0] for h in hs)
    print('control:', 'PASS (alteration detected as', len(hs), 'hunks)' if ok else f'FAIL ({hs})')
    # real transitions: v7 -> v7.1 is exactly the table rule (5 added lines, 1 changed numbering line)
    real = hunks(prompt_lines('llm-service.local-v7.js'), prompt_lines('llm-service.local-v71.js'))
    print('v7 -> v7.1 hunks:', len(real))
    return ok


if __name__ == '__main__':
    if '--control' in sys.argv:
        sys.exit(0 if control() else 1)
    run_report()
